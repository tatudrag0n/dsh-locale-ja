/**
 * Bundle the authored dictionaries into the client module the browser loads.
 *
 * `client.src.js` owns the behaviour, `dictionaries/*.json` own the data, and
 * this tool joins them into the single `client.js` artifact: the client-modules
 * node half serves exactly one bundle file per package, so the dictionaries
 * travel inside it instead of as a second HTTP request.
 *
 * Usage:
 *   node tools/build.mjs           write client.js
 *   node tools/build.mjs --check   exit 1 when client.js is not current
 *
 * @module tools/build
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dirname, '..')
const dictionariesDir = join(root, 'dictionaries')
const sourceFile = join(root, 'client.src.js')
const outputFile = join(root, 'client.js')
/** The placeholder `client.src.js` leaves for the generated dictionary table. */
const PLACEHOLDER = '__DICTIONARIES__'

/** Keys that cannot be spelled as a plain object-literal property name. */
const COMPUTED_KEYS = new Set(['__proto__'])

/**
 * Read every namespace that carries at least one translation.
 * @returns namespace → ordered [key, japanese] pairs.
 */
export function collectDictionaries() {
  const namespaces = new Map()
  for (const file of readdirSync(dictionariesDir).sort()) {
    if (!file.endsWith('.json') || file === 'index.json') continue
    const record = JSON.parse(readFileSync(join(dictionariesDir, file), 'utf8'))
    const entries = Object.entries(record.ja ?? {})
      .filter(([, value]) => typeof value === 'string')
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    if (entries.length === 0) continue
    namespaces.set(record.namespace, entries)
  }
  return namespaces
}

/**
 * Render the dictionary table as JavaScript source.
 * @param namespaces - output of {@link collectDictionaries}.
 * @returns the object-literal source for the `DICTIONARIES` binding.
 */
export function renderDictionaries(namespaces) {
  const lines = ['{']
  for (const [namespace, entries] of namespaces) {
    lines.push(`\t\t\t${JSON.stringify(namespace)}: {`)
    for (const [key, value] of entries) {
      /* A `__proto__` key written plainly would set the prototype instead of a
         property, so that one key is spelled as a computed name. */
      const name = COMPUTED_KEYS.has(key) ? `[${JSON.stringify(key)}]` : JSON.stringify(key)
      lines.push(`\t\t\t\t${name}: ${JSON.stringify(value)},`)
    }
    lines.push('\t\t\t},')
  }
  lines.push('\t\t}')
  return lines.join('\n')
}

/** Render the whole `client.js` artifact. */
export function renderBundle() {
  const namespaces = collectDictionaries()
  const source = readFileSync(sourceFile, 'utf8')
  const marker = `${'const DICTIONARIES = '}${PLACEHOLDER};`
  if (!source.includes(marker)) throw new Error(`client.src.js no longer contains "${marker}"`)
  const banner = [
    '/* Generated by tools/build.mjs from client.src.js and dictionaries/*.json.',
    ` * ${String([...namespaces.values()].reduce((sum, entries) => sum + entries.length, 0))} translated keys across ${String(namespaces.size)} namespaces.`,
    ' * Edit those sources and re-run `npm run build`; edits here are overwritten. */',
  ].join('\n')
  const body = source.replace(marker, `const DICTIONARIES = ${renderDictionaries(namespaces)};`)
  return `${banner}\n${body}`
}

function main(argv) {
  const rendered = renderBundle()
  if (argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(outputFile, 'utf8')
    } catch {
      current = ''
    }
    if (current !== rendered) {
      process.stderr.write('client.js is stale: run `node tools/build.mjs`\n')
      process.exitCode = 1
      return
    }
    process.stdout.write('client.js is current\n')
    return
  }
  writeFileSync(outputFile, rendered, 'utf8')
  const namespaces = collectDictionaries()
  process.stdout.write(`client.js written: ${String(namespaces.size)} namespaces, ${String([...namespaces.values()].reduce((sum, entries) => sum + entries.length, 0))} keys\n`)
}

if (process.argv[1] === import.meta.filename) main(process.argv.slice(2))
